def seq(name, title, objs, msgs):
    idx = {n: i for i, (n, _) in enumerate(objs)}
    return {'type': 'seq', 'name': name, 'title': title, 'objs': objs,
            'msgs': [(idx[a], idx[b], t, r) for a, b, t, r in msgs]}


def act(name, title, lanes, nodes, edges, objects=()):
    return {'type': 'act', 'name': name, 'title': title, 'lanes': lanes,
            'nodes': {n[0]: n[1:] for n in nodes}, 'edges': edges, 'objects': list(objects)}


