def branch_flow(name, title, lanes, actor, steps_before, check, bad, good_steps, objects=(), bad_back=None):
    """Common shape: start -> steps -> system check -> decision -> [Khong hop le] bad -> (back|end) / [Hop le] good -> end.
    steps_before: [(text, lane)], good_steps: [(text, lane)]."""
    nodes, edges, row = [('s', 'start', '', steps_before[0][1], 0, 0)], [], 1
    prev = 's'
    for k, (text, lane) in enumerate(steps_before):
        nid = 'b%d' % k
        nodes.append((nid, 'act', text, lane, row, 0)); edges.append((prev, nid, '')); prev = nid; row += 1
    nodes.append(('chk', 'act', check, 1, row, 0)); edges.append((prev, 'chk', '')); row += 1
    nodes.append(('d', 'dec', '', 1, row, 0)); edges.append(('chk', 'd', '')); row += 1
    bad_text, bad_lane = bad
    nodes.append(('bad', 'act', bad_text, bad_lane, row, -1 if bad_lane == 1 else 0))
    edges.append(('d', 'bad', '[Khong hop le]'))
    last = 'd'
    for k, (text, lane) in enumerate(good_steps):
        nid = 'g%d' % k
        nodes.append((nid, 'act', text, lane, row, 1 if (lane == 1 and k == 0 and bad_lane == 1) else 0))
        edges.append((last, nid, '[Hop le]' if k == 0 else '')); last = nid; row += 1
    nodes.append(('e', 'end', '', good_steps[-1][1], row, 0)); edges.append((last, 'e', ''))
    edges.append(('bad', bad_back if bad_back else 'e', ''))
    objs = [(o, lane, r_, col, a) for o, lane, r_, col, a in objects]
    return act(name, title, lanes, nodes, edges, objs)


def two_way(name, title, lanes, steps_before, decide_lane, left, right, after=(), objects=()):
    """start -> steps -> decision -> left branch / right branch (each a list of (text, lane)) -> optional common steps -> end."""
    nodes, edges, row = [('s', 'start', '', steps_before[0][1], 0, 0)], [], 1
    prev = 's'
    for k, (text, lane) in enumerate(steps_before):
        nid = 'b%d' % k
        nodes.append((nid, 'act', text, lane, row, 0)); edges.append((prev, nid, '')); prev = nid; row += 1
    nodes.append(('d', 'dec', '', decide_lane, row, 0)); edges.append((prev, 'd', '')); row += 1
    tails, depth = [], 0
    for side, (guard, steps) in ((-1, left), (1, right)):
        p = 'd'
        for k, (text, lane) in enumerate(steps):
            nid = '%s%d' % ('l' if side < 0 else 'r', k)
            nodes.append((nid, 'act', text, lane, row + k, side))
            edges.append((p, nid, guard if k == 0 else '')); p = nid
        tails.append(p); depth = max(depth, len(steps))
    row += depth
    if after:
        for k, (text, lane) in enumerate(after):
            nid = 'a%d' % k
            nodes.append((nid, 'act', text, lane, row, 0))
            if k == 0:
                for t in tails:
                    edges.append((t, nid, ''))
            else:
                edges.append(('a%d' % (k - 1), nid, ''))
            row += 1
        nodes.append(('e', 'end', '', after[-1][1], row, 0)); edges.append(('a%d' % (len(after) - 1), 'e', ''))
    else:
        nodes.append(('e', 'end', '', decide_lane, row, 0))
        for t in tails:
            edges.append((t, 'e', ''))
    return act(name, title, lanes, nodes, edges, list(objects))


