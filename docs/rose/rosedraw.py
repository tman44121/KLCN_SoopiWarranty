"""Draw UML diagrams in a running Rational Rose 2006 via COM, then export crisp images.

Pipeline (see docs/ROSE_DIAGRAMS.md):
  1. build(): create sequence/activity diagrams in the open Rose model from specs.
  2. SaveAs .mdl, fix_petal(): move object labels under their icons, shift messages below them, enable message numbers.
  3. OpenModel(fixed) and render_all(): RenderEnhanced each diagram to EMF.
  4. emf_to_png(): GDI+ rasterise at high scale, crop to content.
Requires: pywin32, Pillow, rosetlb.py generated by makepy (path in ROSETLB_DIR or next to this file).
"""
import os, re, sys, time, subprocess
import win32com.client as w
from PIL import Image

sys.path.insert(0, os.environ.get('ROSETLB_DIR', os.path.dirname(os.path.abspath(__file__))))
import rosetlb  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
RETURN = 6  # Synchronization value Rose draws as a dashed return message
LANE_W, ROW_H, TOP = 1700, 240, 130
BRANCH_DX, OBJECT_DX, OBJECT_W = 280, 680, 290  # object (±145) stays clear of branch nodes and inside its lane
ACT_LABEL_W = 420
ACT_MIN_W = 470
SEQ_X_SCALE = 1.3
ZOOM = 150  # written into every diagram of the fixed .mdl; capture.py screenshots Rose at this zoom


def app():
    return rosetlb.IRoseApplication(w.GetActiveObject('Rose.Application')._oleobj_)


# ------------------------------------------------------------------ sequence
def build_sequence(cat, spec, classes):
    for name, st in spec['objs']:
        ensure_class(classes, name, st)
    d = cat.AddScenarioDiagram(spec['name'], 1)
    d.Activate()
    objs = [d.AddInstance('', name) for name, _ in spec['objs']]
    for o in objs:
        d.AddInstanceView(o, True)
    for i, (a, b, text, ret) in enumerate(spec['msgs'], 1):
        d.CreateMessage(text, objs[a], objs[b], i).Synchronization = RETURN if ret else 0
    return d


# ------------------------------------------------------------------ activity
def ensure_class(classes, name, stereotype):
    if name not in classes['map']:
        c = classes['cat'].AddClass(name)
        c.Stereotype = stereotype
        classes['map'][name] = c


def build_activity(cat, spec, classes=None):
    """nodes: id -> (kind, text, lane, row, col); kind in start/end/act/dec. col: -1, 0, 1 within the lane."""
    holder = cat.AddClass(spec['name'] + '_QuyTrinh')
    sm = holder.StateMachineOwner.CreateStateMachine('SM_' + spec['name'])
    d = sm.AddActivityDiagram(spec['name'])
    d.Activate()
    lanes = [sm.AddSwimLane(n) for n in spec['lanes']]
    lane_views = [d.AddSwimLaneView(l) for l in lanes]
    items, views = {}, {}
    for nid, (kind, text, lane, row, col) in spec['nodes'].items():
        if kind in ('start', 'end'):
            s = sm.AddState('')
            s.StateKind.Value = 1 if kind == 'start' else 2
            items[nid], views[nid] = s, d.AddStateView(s)
        elif kind == 'dec':
            dd = sm.AddDecision('')
            items[nid], views[nid] = dd, d.AddDecisionView(dd)
        else:
            a = sm.AddActivity(text)
            items[nid], views[nid] = a, d.AddActivityView(a)
    for a, b, label in spec['edges']:
        d.AddRelationView(items[a].AddTransitionToVertex(label, items[b]))
    obj_views = []
    for oname, lane, row, col, act_id in spec.get('objects', []):
        o = sm.AddObjectInstance(oname)
        flow = items[act_id].AddObjectFlow(o)
        ov = d.AddObjectInstanceView(o)
        obj_views.append((ov, lane, row, col))
        try:
            d.AddRelationView(flow)
        except Exception:
            pass
    d.AutosizeAll()
    lw = spec.get('lane_w', LANE_W)
    bdx = spec.get('branch_dx', BRANCH_DX)
    for lv in lane_views:
        lv.Width = lw
    def place(v, lane, row, col):
        v.XPosition = int(lw * lane + lw / 2 + col * bdx)
        v.YPosition = TOP + row * ROW_H
    for nid, (kind, text, lane, row, col) in spec['nodes'].items():
        if kind == 'act' and views[nid].Width < ACT_MIN_W:
            views[nid].Width = ACT_MIN_W  # wider node: Rose wraps the name instead of cutting it with "..."
        place(views[nid], lane, row, col)
    for ov, lane, row, col in obj_views:
        ov.Width = OBJECT_W
        ov.XPosition = int(lw * lane + lw / 2 + col * (OBJECT_DX - (LANE_W - lw) / 2))
        ov.YPosition = TOP + row * ROW_H
    return d


def settle(r, workdir):
    """Save the open model so OpenModel never stops on a "Save Changes?" dialog.
    A model that already lives in workdir is saved in place; anything else is copied to a backup file there."""
    m = r.CurrentModel
    if m is None or not m.IsModified():
        return
    fn = m.GetFileName() or ''
    if fn and os.path.abspath(fn).lower().startswith(os.path.abspath(workdir).lower()):
        m.Save()
    else:
        m.SaveAs(os.path.join(workdir, 'backup_%d.mdl' % int(time.time())))


def build(specs, category_name, workdir):
    """Start from an empty model saved in workdir (class names resolve uniquely), then build every spec."""
    r = app()
    settle(r, workdir)
    r.OpenModel(os.path.join(HERE, 'empty.mdl'))
    time.sleep(1)
    m = r.CurrentModel
    m.SaveAs(os.path.join(workdir, category_name + '_work.mdl'))
    root = m.RootCategory
    classes = {'cat': root.AddCategory('DoiTuong'), 'map': {}}
    cat = root.AddCategory(category_name)
    for spec in specs:
        if spec['type'] == 'seq':
            build_sequence(cat, spec, classes)
        else:
            build_activity(cat, spec)
    return r, m


def produce(specs, category_name, workdir, scale=3, capture_only=None):
    """Full pipeline: build -> save -> fix petal -> reopen -> capture each diagram as Rose paints it. Returns PNG paths."""
    os.makedirs(workdir, exist_ok=True)
    r, m = build(specs, category_name, workdir)
    raw = os.path.join(workdir, category_name + '_raw.mdl')
    fixed = os.path.join(workdir, category_name + '.mdl')
    m.SaveAs(raw)
    fix_petal(raw, fixed)
    r.OpenModel(fixed)
    time.sleep(1)
    pngs = []
    import capture
    with capture.OffscreenLarge():
        for d in diagrams_of(r.CurrentModel, category_name):
            if capture_only and not d.Name.startswith(capture_only):
                continue
            png = os.path.join(workdir, d.Name + '.png')
            capture.capture_full(d, png)
            capture.crop_content(png)
            if d.Name.startswith('AD_'):
                capture.crop_after_last_lane(png)
            pngs.append(png)
    settle(r, workdir)
    return pngs


# ------------------------------------------------------------------ petal fix
_loc = re.compile(r'^(\s*location\s*)\((-?\d+), (-?\d+)\)')
_pt = re.compile(r'^(\s*(?:origin|terminus)\s*)\((-?\d+), (-?\d+)\)')


def _depth(line):
    s = re.sub(r'"[^"]*"', '', line)  # labels may contain parentheses
    return s.count('(') - s.count(')')


def _span(block, k):
    """Index just past the petal object that starts on line k."""
    depth = 0
    for j in range(k, len(block)):
        depth += _depth(block[j])
        if depth <= 0:
            return j + 1
    return len(block)


def _diagram_blocks(lines, marker):
    i = 0
    while i < len(lines):
        if marker in lines[i]:
            j = _span(lines, i)
            yield i, j
            i = j
        else:
            i += 1


def fix_petal(src, dst):
    lines = open(src, encoding='latin-1').read().split('\n')
    for marker, fixer in (('(object InteractionDiagram', _fix_interaction), ('(object ActivityDiagram', _fix_activity)):
        out, last = [], 0
        for i, j in _diagram_blocks(lines, marker):
            out.extend(lines[last:i + 1])
            out.extend(fixer(lines[i + 1:j]))
            last = j
        out.extend(lines[last:])
        lines = out
    text = '\n'.join(lines)
    text = re.sub(r'showMessageNum \t\d', 'showMessageNum \t3', text)
    text = re.sub(r'(\n\s*zoom\s+)100\b', lambda m: m.group(1) + str(ZOOM), text)
    open(dst, 'w', encoding='latin-1').write(text)


_lane_hdr = re.compile(r'\(object Swimlane "([^"]*)" (@\d+)')


def _fix_activity(block):
    """Equal-width contiguous swimlanes; drop the unnamed lane Rose adds for object views."""
    lanes, objviews, k = [], [], 0
    while k < len(block):
        m = _lane_hdr.search(block[k])
        if m:
            e = _span(block, k)
            lanes.append((m.group(1), m.group(2), k, e))
            k = e
            continue
        if '(object ObjectView' in block[k]:
            e = _span(block, k)
            ox = next((int(_loc.match(l).group(2)) for l in block[k:e] if _loc.match(l)), 0)
            objviews.append((k, e, ox))
            k = e
            continue
        k += 1
    named = [l for l in lanes if l[0]]
    lw = next((int(l.split()[-1].rstrip(')')) for _, _, s, e in named[:1] for l in block[s:e]
               if l.strip().startswith('width')), LANE_W)
    lane_x = {ref: n * lw for n, (_, ref, _, _) in enumerate(named)}
    dropped = {ref for name, ref, _, _ in lanes if not name}
    starts = {s: (name, ref, e) for name, ref, s, e in lanes}
    res, k, in_activity = [], 0, False
    while k < len(block):
        if k in starts:
            name, ref, e = starts[k]
            if ref in lane_x:
                ind = block[k + 1][:len(block[k + 1]) - len(block[k + 1].lstrip())] if k + 1 < e else '\t'
                res.append(block[k])
                res.append('%slocation   \t(%d, 0)' % (ind, lane_x[ref]))
                res.extend(l for l in block[k + 1:e] if l.strip().startswith(('line_color', 'quidu')))
                res.append('%swidth      \t%d)' % (ind, lw))
            k = e
            continue
        line = block[k]
        if '(object ' in line:
            in_activity = '(object ActivityStateView' in line or (in_activity and '(object ItemLabel' in line)
        if in_activity and line.strip().startswith('max_width'):
            line = re.sub(r'\d+$', str(ACT_LABEL_W), line)  # Rose cuts long activity names with "..." otherwise
        if dropped and 'Parent_View' in line:
            ref = line.split()[-1]
            if ref in dropped:
                ov = next((o for o in objviews if o[0] < k < o[1]), None)
                ox = ov[2] if ov else 0
                target = next((r for r, x in lane_x.items() if x <= ox < x + lw), list(lane_x)[-1])
                line = line.replace(ref, target)
        res.append(line)
        k += 1
    return _route_activity(res)


# ------------------------------------------------------------------ activity edge routing
_view_hdr = re.compile(r'\(object (ActivityStateView|DecisionView|StateView|ObjectView)\b.*(@\d+)\s*$')
_SIZE = {'ActivityStateView': (470, 106), 'DecisionView': (100, 60), 'StateView': (50, 50), 'ObjectView': (290, 126)}
MARGIN, GAP = 14, 130


def _own_lines(block, s, e):
    """Lines of the object starting at s that are not inside a nested object."""
    depth = 0
    for j in range(s, e):
        if depth == 1:
            yield j, block[j]
        depth += _depth(block[j])


def _hits(seg, box):
    (x1, y1), (x2, y2) = seg
    l, t, r, b = box
    n = max(2, int(max(abs(x2 - x1), abs(y2 - y1)) / 8))
    return any(l < x1 + (x2 - x1) * i / n < r and t < y1 + (y2 - y1) * i / n < b for i in range(n + 1))


def _seg_box(a, b, trim=24):
    """Thin box around a routed segment, shortened at both ends so edges may still meet at a node."""
    (x1, y1), (x2, y2) = sorted([a, b])
    if x1 == x2:
        return (x1 - 18, y1 + trim, x1 + 18, y2 - trim)
    return (x1 + trim, min(y1, y2) - 18, x2 - trim, max(y1, y2) + 18)


def _clear(path, boxes):
    return all(not _hits((path[i], path[i + 1]), bx) for i in range(len(path) - 1) for bx in boxes)


def _paths(S, T, lanes_x):
    """Candidate orthogonal paths from view S to view T, best first. A view is (kind, cx, cy, hw, hh)."""
    sk, sx, sy, sw, sh = S
    tk, tx, ty, tw, th = T
    out = []
    if ty > sy:
        if abs(sx - tx) < 4:
            out.append([(sx, sy + sh), (tx, ty - th)])
        side = sw if tx > sx else -sw
        l_side = [(sx + side, sy), (tx, sy), (tx, ty - th)]
        z = lambda ym: [(sx, sy + sh), (sx, ym), (tx, ym), (tx, ty - th)]
        l_down = [(sx, sy + sh), (sx, ty), (tx - tw if tx > sx else tx + tw, ty)]
        mid = (sy + sh + ty - th) / 2
        if sk == 'DecisionView':
            out += [l_side, z(ty - th - GAP / 2), l_down, z(mid)]
        else:
            out += [z(mid), z(ty - th - GAP / 2), z(sy + sh + GAP / 2), l_down, l_side]
    xs = []
    for base in (sx, tx):
        for k in range(1, 12):
            xs += [base - sw - 50 * k, base + sw + 50 * k, base - tw - 50 * k, base + tw + 50 * k]
    xs += [x + d for x in lanes_x for d in (70, -70, 120, -120)]
    for X in sorted(set(int(x) for x in xs), key=lambda x: abs(x - sx) + abs(x - tx)):
        a = (sx - sw, sy) if X < sx else (sx + sw, sy)
        b = (tx - tw, ty) if X < tx else (tx + tw, ty)
        out.append([a, (X, sy), (X, ty), b])
    return out


def _route_activity(block):
    """Give every transition an orthogonal path that does not cross other activities, decisions, states or objects."""
    views, trans = {}, []
    lanes_x = [0]
    k = 0
    while k < len(block):
        line = block[k]
        m = _view_hdr.search(line)
        if m and '(object TransView' not in line:
            e = _span(block, k)
            kind, ref = m.group(1), m.group(2)
            w, h = _SIZE[kind]
            cx = cy = None
            for _, l in _own_lines(block, k, e):
                s = l.strip()
                if s.startswith('location') and cx is None:
                    cx, cy = map(int, re.findall(r'-?\d+', s)[:2])
                elif s.startswith('width'):
                    w = int(re.findall(r'\d+', s)[0])
                elif s.startswith('height'):
                    h = int(re.findall(r'\d+', s)[0])
            views[ref] = (kind, cx, cy, w / 2, h / 2)
            k += 1
            continue
        if '(object Swimlane' in line:
            e = _span(block, k)
            lx = next((int(re.findall(r'-?\d+', l)[0]) for l in block[k:e] if l.strip().startswith('location')), None)
            lw = next((int(re.findall(r'\d+', l)[0]) for l in block[k:e] if l.strip().startswith('width')), None)
            if lx is not None and lw:
                lanes_x += [lx, lx + lw]
        if '(object TransView' in line:
            trans.append((k, _span(block, k)))
        k += 1
    edits = {}
    routed = []
    for s, e in trans:
        own = dict((l.strip().split()[0], (j, l)) for j, l in _own_lines(block, s, e) if l.strip())
        try:
            S, T = views[own['client'][1].split()[-1]], views[own['supplier'][1].split()[-1]]
        except KeyError:
            continue
        boxes = [(v[1] - v[3] - MARGIN, v[2] - v[4] - MARGIN, v[1] + v[3] + MARGIN, v[2] + v[4] + MARGIN)
                 for v in views.values() if v not in (S, T)]
        cands = _paths(S, T, sorted(set(lanes_x)))
        path = next((p for p in cands if _clear(p, boxes) and _clear(p, routed)), None) \
            or next((p for p in cands if _clear(p, boxes)), cands[0])
        routed += [_seg_box(a, b) for a, b in zip(path, path[1:])]
        vs = own['vertices'][0]
        ve = _span(block, vs)
        ind = block[vs + 1][:len(block[vs + 1]) - len(block[vs + 1].lstrip())]
        pts = ['%s(%d, %d)' % (ind, x, y) for x, y in path]
        pts[-1] += ')'
        edits[vs] = (ve, [block[vs].split('(list')[0] + '(list Points'] + pts)
        # guard label next to the first segment
        for j in range(s, e):
            if '(object SegLabel' in block[j]:
                le = _span(block, j)
                text = next((re.findall(r'"([^"]*)"', l)[0] for l in block[j:le] if l.strip().startswith('label') and '"' in l), '')
                (x1, y1), (x2, y2) = path[0], path[1]
                if y1 == y2:
                    lx, ly = (x1 + x2) / 2, y1 - 28
                else:
                    lx, ly = x1 + 14 + 7 * len(text), y1 + 40
                for jj in range(j, le):
                    if block[jj].strip().startswith('location'):
                        edits[jj] = (jj + 1, [re.sub(r'\(-?\d+, -?\d+\)', '(%d, %d)' % (lx, ly), block[jj])])
                    elif block[jj].strip().startswith('pctDist'):
                        edits[jj] = (jj + 1, [block[jj]])
                break
    out, k = [], 0
    while k < len(block):
        if k in edits:
            end, new = edits[k]
            out.extend(new)
            k = end
        else:
            out.append(block[k])
            k += 1
    return out


def _fix_interaction(block):
    # pass 1: object locations, icon heights, first message y
    objs, cur, kind, label_line = [], None, None, {}
    msg_ys = []
    for k, l in enumerate(block):
        s = l.strip()
        if s.startswith('(object InterObjView'):
            cur = {'loc': None, 'icon_h': 150, 'label': None}; objs.append(cur); kind = 'obj'
        elif s.startswith('(object InterMessView') or s.startswith('(object SelfMessView'):
            kind = 'msg'
        elif s.startswith('label') and '(object ItemLabel' in s and kind == 'obj':
            kind = 'objlabel'
        elif s.startswith('(object Focus_Of_Control'):
            kind = 'focus'
        m = _loc.match(l)
        if m:
            if kind == 'obj' and cur['loc'] is None:
                cur['loc'] = (k, int(m.group(3)))
            elif kind == 'objlabel' and cur['label'] is None:
                cur['label'] = k; kind = 'obj'
        m2 = _pt.match(l)
        if m2 and 'origin' in l:
            msg_ys.append(int(m2.group(3)))
        if s.startswith('icon_height') and cur is not None:
            cur['icon_h'] = int(s.split()[-1])
    if not objs or not msg_ys:
        return block
    label_y = {}
    for o in objs:
        y = o['loc'][1]
        label_y[o['label']] = y + o['icon_h'] // 2 + 38
    first_needed = max(label_y.values()) + 75
    shift = max(0, first_needed - min(msg_ys))
    xs = [int(_loc.match(block[o['loc'][0]]).group(2)) for o in objs]
    x0 = min(xs)
    sx = lambda x: int(x0 + (x - x0) * SEQ_X_SCALE)
    # pass 2: rewrite
    res, kind = [], None
    for k, l in enumerate(block):
        s = l.strip()
        if s.startswith('(object InterObjView'):
            kind = 'obj'
        elif s.startswith('(object InterMessView') or s.startswith('(object SelfMessView') or s.startswith('(object Focus_Of_Control'):
            kind = 'shift'
        if k in label_y:
            m = _loc.match(l)
            l = '%s(%d, %d)' % (m.group(1), sx(int(m.group(2))), label_y[k])
        else:
            m = _loc.match(l) or _pt.match(l)
            if m:
                dy = shift if kind == 'shift' else 0
                l = '%s(%d, %d)' % (m.group(1), sx(int(m.group(2))), int(m.group(3)) + dy)
        if s.startswith('max_width') and kind is not None:  # never touch the diagram's own max_width
            l = re.sub(r'(\d+)$', '1200' if kind == 'shift' else '700', l)
        if kind == 'obj' and s.startswith('height') and shift:
            l = re.sub(r'(\d+)$', lambda mm: str(int(mm.group(1)) + shift), l)
        res.append(l)
    return res


# ------------------------------------------------------------------ render
def diagrams_of(m, category_name):
    cat = None
    cats = m.RootCategory.Categories
    for i in range(1, cats.Count + 1):
        if cats.GetAt(i).Name == category_name:
            cat = cats.GetAt(i)
    diagrams = []
    sds = cat.ScenarioDiagrams
    for i in range(1, sds.Count + 1):
        diagrams.append(sds.GetAt(i))
    classes = cat.Classes
    for i in range(1, classes.Count + 1):
        sms = classes.GetAt(i).StateMachineOwner.StateMachines
        for j in range(1, sms.Count + 1):
            ds = sms.GetAt(j).Diagrams
            for k in range(1, ds.Count + 1):
                diagrams.append(ds.GetAt(k))
    return diagrams


def render_all(m, outdir, category_name, names=None):
    """EMF export (vector). Kept for reference; the report uses capture.py, which matches Rose's on-screen look."""
    os.makedirs(outdir, exist_ok=True)
    diagrams = diagrams_of(m, category_name)
    done = []
    for d in diagrams:
        if names and d.Name not in names:
            continue
        f = os.path.join(outdir, d.Name + '.emf')
        if os.path.exists(f):
            os.remove(f)
        d.Activate()
        d.RenderEnhanced(f)
        for _ in range(40):
            if os.path.exists(f) and os.path.getsize(f) > 500:
                break
            time.sleep(0.25)
        time.sleep(0.3)
        done.append(f)
    return done


def emf_to_png(emf, png, scale=4):
    subprocess.run(['powershell', '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', os.path.join(HERE, 'render.ps1'),
                    emf, png, str(scale)], check=True, capture_output=True)
    im = Image.open(png).convert('RGB')
    gray = im.convert('L')
    wdt, hgt = gray.size
    px = gray.load()
    rows = []
    for y in range(hgt):
        dark = sum(1 for x in range(0, wdt, 2) if px[x, y] < 235)
        rows.append(dark)
    # swimlane/lifeline rows only contain a few thin vertical lines; content rows have more dark pixels
    lane_level = sorted(rows)[len(rows) // 2]
    content = [y for y, c in enumerate(rows) if c > lane_level + 6]
    bb = Image.eval(gray, lambda p: 255 if p < 235 else 0).getbbox()
    if not bb:
        return
    bottom = min(bb[3], (content[-1] if content else bb[3]) + int(25 * scale))
    pad = int(6 * scale)
    box = (max(0, bb[0] - pad), max(0, bb[1] - pad), min(wdt, bb[2] + pad), min(hgt, bottom + pad))
    im.crop(box).save(png, dpi=(300, 300))
